import { useState } from 'react';
import { Button, Dropdown, Spinner } from 'react-bootstrap';
import { postData } from '../../services/api-services';
import { API_URL_TICKETS } from '../../services/config';
import { notifyOpsChanged } from '../../services/ops-service';
import type { CreateTicketRequest, TicketCategory } from '../../types/models';

interface Scenario {
    label: string;
    category: TicketCategory;
    affectedSystem: string;
    titles: string[];
}

const scenarios: Scenario[] = [
    {
        label: 'VPN outage',
        category: 'VPN',
        affectedSystem: 'VPN',
        titles: ["VPN won't connect", 'VPN keeps dropping', 'Cannot reach intranet over VPN', 'VPN login times out', 'VPN down for me too'],
    },
    {
        label: 'Email outage',
        category: 'EMAIL',
        affectedSystem: 'Outlook',
        titles: ['Outlook not syncing', 'Cannot send emails', 'Outlook stuck on loading', 'Emails not arriving', 'Outlook disconnected'],
    },
    {
        label: 'Wi-Fi outage',
        category: 'NETWORK',
        affectedSystem: 'Office Wi-Fi',
        titles: ['No Wi-Fi on 2nd floor', 'Wi-Fi keeps disconnecting', 'Cannot join office Wi-Fi', 'Internet very slow', 'Wi-Fi gone in meeting room'],
    },
];

const people = ['alice', 'bob', 'carol', 'dan', 'emma'];
const DELAY_MS = 700;

const wait = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

export default function DemoOutageButton() {
    const [running, setRunning] = useState<string | null>(null);
    const [progress, setProgress] = useState(0);
    const [result, setResult] = useState<string | null>(null);

    const run = async (scenario: Scenario) => {
        setRunning(scenario.label);
        setProgress(0);
        setResult(null);
        const runId = Date.now().toString(36);
        let created = 0;
        let incidentId: number | null = null;
        for (let i = 0; i < scenario.titles.length; i++) {
            const request: CreateTicketRequest = {
                title: scenario.titles[i],
                description: 'Generated by the demo button',
                category: scenario.category,
                affectedSystem: scenario.affectedSystem,
                requesterEmail: `${people[i % people.length]}.${runId}@demo.com`,
                priority: 'HIGH',
            };
            try {
                const ticket = await postData<{ incidentId: number | null }>(API_URL_TICKETS, request);
                created++;
                if (ticket.incidentId != null) incidentId = ticket.incidentId;
            } catch (err) {
                console.warn('Demo report failed:', err);
            }
            setProgress(i + 1);
            notifyOpsChanged();
            if (i < scenario.titles.length - 1) await wait(DELAY_MS);
        }
        setResult(
            incidentId != null
                ? `${created} reports sent, grouped into incident #${incidentId}`
                : `${created} reports sent`
        );
        setRunning(null);
        notifyOpsChanged();
    };

    if (running) {
        return (
            <Button variant="danger" size="sm" disabled>
                <Spinner animation="border" size="sm" className="me-1" />
                {running}: report {progress}/{scenarios[0].titles.length}
            </Button>
        );
    }

    return (
        <div className="d-flex align-items-center gap-2">
            {result && <small className="text-success">{result}</small>}
            <Dropdown>
                <Dropdown.Toggle variant="danger" size="sm">
                    🎬 Simulate outage
                </Dropdown.Toggle>
                <Dropdown.Menu align="end">
                    {scenarios.map((s) => (
                        <Dropdown.Item key={s.label} onClick={() => run(s)}>
                            {s.label} ({s.titles.length} reports)
                        </Dropdown.Item>
                    ))}
                </Dropdown.Menu>
            </Dropdown>
        </div>
    );
}
